#!/usr/bin/env python3
"""Regenerate hidden_modules.txt (the precomputed collect_submodules() result).

gato.spec cannot call collect_submodules() because PyInstaller runs that walk in an isolated
child interpreter, and that child dies under Wine (unimplemented ucrtbase.dll.crealf), killing
the build. So the module list is generated here once, on the build interpreter, and read back
by the spec.

    python dev/tools/gen_hidden_modules.py [--check]

--check exits 1 when the file is stale (a package gained or lost modules since it was written).
"""
import os
import pkgutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'hidden_modules.txt')
ROOTS = ('ultralytics', 'numpy._core')
HEADER = '# generated by dev/tools/gen_hidden_modules.py -- do not edit by hand'


def walk(root):
    """Every importable submodule of root, including root itself."""
    out = []
    try:
        mod = __import__(root, fromlist=['__path__'])
    except Exception as e:
        raise SystemExit(f'cannot import {root}: {type(e).__name__}: {e}')
    out.append(root)
    for info in pkgutil.walk_packages(getattr(mod, '__path__', []), root + '.'):
        out.append(info.name)
    return out


def render():
    mods = sorted({m for root in ROOTS for m in walk(root)})
    return HEADER + chr(10) + chr(10).join(mods) + chr(10)


def main():
    body = render()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old != body:
            print(f'STALE {OUT}')
            return 1
        print('ok')
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(body)
    print(f'wrote {len(body.splitlines()) - 1} modules to {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
